/**
 * dsh-workspace-progress — workspace-level progress sharing for DeepSeek
 * Harness sessions.
 *
 * Pipeline:
 *   session/event  -> evidence facts -> per-session state + append-only log
 *   turn/end       -> persist session state, schedule a coalesced render
 *   agent/pre-step -> inject the bounded summary once per session
 *   /progress      -> status, sync, refresh, note, on/off, archive
 *
 * Design constraints: zero model calls, no raw tool output on disk, no
 * blocking of the agent loop, and per-session files that never contend.
 */
import { randomUUID } from 'node:crypto'
import path from 'node:path'
import { stat } from 'node:fs/promises'

import { aggregateStates, formatTime } from './lib/aggregate.js'
import {
  assistantClaimSummary,
  buildPendingCall,
  factFromUserMessage,
  factsFromToolResult,
  turnStatus,
} from './lib/evidence.js'
import {
  PLUGIN_NAME,
  mergeWorkspaceConfig,
  resolveConfig,
  sanitizeText,
} from './lib/policy.js'
import { resolveWorkspace, samePath } from './lib/paths.js'
import { renderInjection, renderProgress, renderSummary } from './lib/render.js'
import { markInjected, markStatus, normalizeSessionState, applyFact, sortBySeq } from './lib/state.js'
import {
  appendJsonl,
  archiveSessionFiles,
  ensureDir,
  listFiles,
  readJson,
  readText,
  withFileLock,
  writeFileAtomic,
  writeJson,
} from './lib/store.js'

export const name = PLUGIN_NAME
export const inject = ['sessions', 'agents', 'commands']

const GITIGNORE = `# Generated by dsh-workspace-progress.
# Raw event logs and per-session state stay local by default.
*
!.gitignore
!progress.md
!summary.md
`

class ProgressEngine {
  constructor(ctx, rawConfig) {
    this.ctx = ctx
    this.baseConfig = resolveConfig(rawConfig)
    this.entries = new Map()
    this.chains = new Map()
    this.workspaces = new Map()
    this.timers = new Set()
    this.disposed = false
    this.version = '1.0.0'
  }

  /* ------------------------------------------------------------------ *
   * lifecycle
   * ------------------------------------------------------------------ */

  async start() {
    const sessions = this.ctx.get('sessions')
    const live = typeof sessions?.list === 'function' ? sessions.list() : []
    for (const session of live) {
      // Capture the committed length now: events beyond it are delivered live.
      const upto = Number(session.seq ?? 0)
      this.enqueue(session, async (entry) => this.recover(entry, upto))
    }
  }

  async dispose() {
    this.disposed = true
    for (const timer of this.timers) clearTimeout(timer)
    this.timers.clear()
    const pending = []
    for (const entry of this.entries.values()) {
      if (!entry.state || entry.disabled) continue
      pending.push(this.flush(entry).catch(() => {}))
    }
    await Promise.race([Promise.all(pending), new Promise((resolve) => setTimeout(resolve, 1500))])
  }

  logWarn(message, error) {
    try {
      this.ctx.logger?.warn?.(`${PLUGIN_NAME}: ${message}${error ? `: ${error?.message ?? error}` : ''}`)
    } catch {
      // Logging must never break the agent loop.
    }
  }

  /* ------------------------------------------------------------------ *
   * session entry management
   * ------------------------------------------------------------------ */

  ensureEntry(session) {
    const id = session?.id
    if (!id) return undefined
    let entry = this.entries.get(id)
    if (entry) {
      entry.session = session
      return entry
    }
    entry = {
      id,
      session,
      ws: null,
      config: this.baseConfig,
      state: null,
      pendingCalls: new Map(),
      turnStats: { turn: 0, calls: 0, failures: 0, edits: 0, tests: 0, passed: 0 },
      buffer: [],
      dirty: false,
      disabled: false,
      ready: null,
    }
    this.entries.set(id, entry)
    entry.ready = this.initEntry(entry).catch((error) => {
      entry.disabled = true
      this.logWarn('session initialization failed', error)
    })
    return entry
  }

  effectiveCwd(session) {
    try {
      const service = this.ctx.get('workingDirectory')
      const value = service?.get?.(session)
      if (typeof value === 'string' && value) return value
    } catch {
      // Fall back to the durable header.
    }
    return session?.header?.cwd ?? null
  }

  async initEntry(entry) {
    const cwd = this.effectiveCwd(entry.session)
    if (!cwd) {
      entry.disabled = true
      return
    }
    const workspace = resolveWorkspace(cwd, { scope: this.baseConfig.scope })
    if (!workspace) {
      entry.disabled = true
      return
    }
    const workspaceConfig = await readJson(path.join(workspace.progressDir, 'config.json'), null)
    const config = mergeWorkspaceConfig(this.baseConfig, workspaceConfig)
    if (!config.enabled) {
      entry.disabled = true
      return
    }
    entry.ws = workspace
    entry.config = config
    const header = entry.session?.header ?? {}
    const file = path.join(workspace.progressDir, 'sessions', `${entry.id}.json`)
    const raw = await readJson(file, null)
    entry.state = normalizeSessionState(raw, {
      id: entry.id,
      cwd,
      root: workspace.root,
      name: workspace.name,
      branch: workspace.git?.branch ?? null,
      worktree: workspace.git?.isWorktree ? workspace.cwd : null,
      createdAt: header.createdAt ?? Date.now(),
    })
    entry.state.branch = workspace.git?.branch ?? entry.state.branch
    markStatus(entry.state, 'live')
    const workspaceState = this.workspaceFor(workspace)
    workspaceState.sessions.add(entry.id)
  }

  workspaceFor(workspace) {
    const existing = this.workspaces.get(workspace.key)
    if (existing) return existing
    const created = { ...workspace, sessions: new Set(), timer: null, refreshing: Promise.resolve(), lastRender: 0 }
    this.workspaces.set(workspace.key, created)
    return created
  }

  enqueue(session, task) {
    const entry = this.ensureEntry(session)
    if (!entry) return Promise.resolve()
    const id = entry.id
    const run = async () => {
      await entry.ready
      if (this.disposed || entry.disabled) return
      await task(entry)
    }
    const previous = this.chains.get(id) ?? Promise.resolve()
    const next = previous.then(run, run).catch((error) => this.logWarn(`event handling failed for ${id}`, error))
    this.chains.set(id, next)
    return next
  }

  /* ------------------------------------------------------------------ *
   * event intake
   * ------------------------------------------------------------------ */

  onSessionEvent(session, event) {
    if (!event || typeof event.type !== 'string') return
    // High-frequency, content-free event types are ignored outright.
    if (IGNORED_EVENTS.has(event.type)) return
    this.enqueue(session, async (entry) => {
      await this.processEvent(entry, event)
    })
  }

  async processEvent(entry, event) {
    const state = entry.state
    const config = entry.config
    if (Number.isFinite(event.seq) && event.seq <= (state.lastSeq ?? 0)) return
    if (Number.isFinite(event.seq)) state.lastSeq = event.seq
    if (WORKSPACE_SENSITIVE_EVENTS.has(event.type)) await this.syncWorkspace(entry)

    switch (event.type) {
      case 'user/message': {
        if (!config.captureUserPrompt) return
        const fact = factFromUserMessage(event, config)
        if (fact) this.record(entry, fact)
        return
      }
      case 'tool/call': {
        const pending = buildPendingCall(event)
        if (pending.callId) entry.pendingCalls.set(pending.callId, pending)
        if (entry.pendingCalls.size > 64) {
          const oldest = entry.pendingCalls.keys().next().value
          entry.pendingCalls.delete(oldest)
        }
        return
      }
      case 'tool/result': {
        const callId = String(event.data?.message?.toolCallId ?? event.data?.message?.source?.callId ?? '')
        const pending = callId ? entry.pendingCalls.get(callId) : undefined
        if (callId) entry.pendingCalls.delete(callId)
        if (!pending) return
        const facts = factsFromToolResult(pending, event, config)
        for (const fact of facts) this.record(entry, fact)
        return
      }
      case 'assistant/message': {
        if (!config.captureAssistantClaims) return
        const claim = assistantClaimSummary(event, config)
        if (claim) this.record(entry, { type: 'claim', ...claim, seq: event.seq })
        return
      }
      case 'turn/start': {
        entry.turnStats = { turn: Number(event.data?.turn ?? 0), calls: 0, failures: 0, edits: 0, tests: 0, passed: 0 }
        markStatus(state, 'live', event.time)
        return
      }
      case 'turn/end': {
        const stats = entry.turnStats
        const status = turnStatus(event.data?.reason)
        this.record(entry, { type: 'turn', turn: Number(event.data?.turn ?? stats.turn ?? 0), status, ...stats, at: event.time, seq: event.seq })
        markStatus(state, 'idle', event.time)
        entry.turnStats = { turn: 0, calls: 0, failures: 0, edits: 0, tests: 0, passed: 0 }
        await this.flush(entry)
        this.scheduleRefresh(entry.ws)
        return
      }
      case 'session/disposed': {
        markStatus(state, 'ended', event.time)
        await this.flush(entry)
        return
      }
      default:
        return
    }
  }

  /** Follow a Session that switched its working directory (working_directory tool). */
  async syncWorkspace(entry) {
    if (!entry.session || !entry.state) return
    const cwd = this.effectiveCwd(entry.session)
    if (!cwd || !entry.ws) return
    if (samePath(cwd, entry.ws.cwd)) return
    await this.flush(entry, true)
    const workspace = resolveWorkspace(cwd, { scope: this.baseConfig.scope })
    if (!workspace) return
    const workspaceConfig = await readJson(path.join(workspace.progressDir, 'config.json'), null)
    const config = mergeWorkspaceConfig(this.baseConfig, workspaceConfig)
    entry.ws = workspace
    entry.config = config
    entry.disabled = !config.enabled
    entry.state.cwd = cwd
    entry.state.root = workspace.root
    entry.state.name = workspace.name
    entry.state.branch = workspace.git?.branch ?? entry.state.branch
    entry.state.worktree = workspace.git?.isWorktree ? cwd : null
    this.workspaceFor(workspace).sessions.add(entry.id)
  }

  record(entry, fact) {
    applyFact(entry.state, fact)
    entry.dirty = true
    if (fact.type === 'tool') {
      entry.turnStats.calls += 1
      if (!fact.ok) entry.turnStats.failures += 1
    } else if (fact.type === 'file') {
      entry.turnStats.edits += 1
    } else if (fact.type === 'test') {
      entry.turnStats.tests += 1
      if (fact.ok) entry.turnStats.passed += 1
    }
    if (Number.isFinite(fact.seq)) {
      entry.buffer.push(compactFact(fact))
      if (entry.buffer.length > 500) entry.buffer.splice(0, entry.buffer.length - 500)
    }
  }

  async flush(entry, force = false) {
    if (!entry.state || entry.disabled || (!entry.dirty && !force)) return
    const ws = entry.ws
    if (!ws) return
    await this.ensureWorkspaceDirs(ws)
    const eventsFile = path.join(ws.progressDir, 'events', `${entry.id}.jsonl`)
    if (entry.buffer.length > 0) {
      await appendJsonl(eventsFile, entry.buffer)
      entry.buffer = []
    }
    const file = path.join(ws.progressDir, 'sessions', `${entry.id}.json`)
    entry.state.root = ws.root
    entry.state.name = ws.name
    entry.state.branch = ws.git?.branch ?? entry.state.branch
    await writeJson(file, entry.state)
    entry.dirty = false
    this.workspaceFor(ws).sessions.add(entry.id)
  }

  /** True when another session in this workspace already recorded meaningful work. */
  async hasOtherProgress(workspace, currentId) {
    const files = await listFiles(path.join(workspace.progressDir, 'sessions'), (name) => name.endsWith('.json'))
    for (const file of files) {
      if (path.basename(file, '.json') === currentId) continue
      const raw = await readJson(file, null)
      if (!raw || !raw.id) continue
      const counts = raw.counts ?? {}
      if ((counts.toolCalls ?? 0) > 0 || (counts.turns ?? 0) > 0 || Object.keys(raw.files ?? {}).length > 0) return true
    }
    return false
  }

  async ensureWorkspaceDirs(workspace) {
    const dir = workspace.progressDir
    await ensureDir(path.join(dir, 'sessions'))
    await ensureDir(path.join(dir, 'events'))
    await ensureDir(path.join(dir, 'archive'))
    const gitignore = path.join(dir, '.gitignore')
    const existing = await readText(gitignore, null)
    if (existing === null) await writeFileAtomic(gitignore, GITIGNORE)
  }

  /* ------------------------------------------------------------------ *
   * recovery
   * ------------------------------------------------------------------ */

  async recover(entry, upto = Number(entry.session?.seq ?? 0)) {
    const session = entry.session
    const state = entry.state
    if (!state) return
    const current = Math.min(Number(session?.seq ?? 0), Number(upto ?? 0))
    if (current > (state.lastSeq ?? 0) && typeof session?.snapshotEvents === 'function') {
      const missed = session
        .snapshotEvents(state.lastSeq ?? 0)
        .filter((event) => Number(event.seq) > (state.lastSeq ?? 0) && Number(event.seq) <= current)
      for (const event of sortBySeq(missed)) await this.processEvent(entry, event)
      await this.flush(entry)
    }
    if (state.status === 'ended') markStatus(state, 'live')
  }

  /* ------------------------------------------------------------------ *
   * rendering
   * ------------------------------------------------------------------ */

  scheduleRefresh(workspace) {
    if (!workspace || this.disposed) return
    const state = this.workspaceFor(workspace)
    if (state.timer) clearTimeout(state.timer)
    const delay = Math.max(0, this.baseConfig.idleDebounceMs)
    const timer = setTimeout(() => {
      this.timers.delete(timer)
      state.timer = null
      this.refreshWorkspace(workspace).catch((error) => this.logWarn('workspace refresh failed', error))
    }, delay)
    this.timers.add(timer)
    state.timer = timer
  }

  async refreshWorkspace(workspace) {
    const state = this.workspaceFor(workspace)
    state.refreshing = state.refreshing.then(() => this.renderWorkspace(workspace)).catch((error) => this.logWarn('render failed', error))
    return state.refreshing
  }

  async renderWorkspace(workspace) {
    const state = this.workspaceFor(workspace)
    await this.ensureWorkspaceDirs(workspace)
    const sessionsDir = path.join(workspace.progressDir, 'sessions')
    const files = await listFiles(sessionsDir, (name) => name.endsWith('.json'))
    const states = []
    for (const file of files) {
      const raw = await readJson(file, null)
      if (!raw || !raw.id) continue
      const live = this.entries.get(raw.id)
      states.push(live?.state && (live.state.updatedAt ?? 0) > (raw.updatedAt ?? 0) ? live.state : raw)
    }
    // Include live sessions that have not been flushed yet.
    for (const entry of this.entries.values()) {
      if (entry.disabled || !entry.state || !entry.ws) continue
      if (entry.ws.key !== workspace.key) continue
      if (!states.some((candidate) => candidate.id === entry.id)) states.push(entry.state)
    }
    const aggregate = aggregateStates(states, workspace, { maxAgeDays: this.baseConfig.maxSessionAgeDays })
    const summary = renderSummary(aggregate, {
      maxTokens: this.baseConfig.summaryMaxTokens,
      maxSessionsInSummary: this.baseConfig.maxSessionsInSummary,
    })
    const progress = renderProgress(aggregate)
    await withFileLock(path.join(workspace.progressDir, '.lock'), async () => {
      await writeFileAtomic(path.join(workspace.progressDir, 'summary.md'), summary + '\n')
      await writeFileAtomic(path.join(workspace.progressDir, 'progress.md'), progress + '\n')
      await writeJson(path.join(workspace.progressDir, 'meta.json'), {
        version: this.version,
        updatedAt: aggregate.updatedAt,
        root: workspace.root,
        name: workspace.name,
        sessionCount: aggregate.totals.sessions,
        otherSessions: aggregate.hasOtherSessions,
        active: aggregate.totals.active,
        totals: aggregate.totals,
      })
    })
    state.lastRender = Date.now()
    return { aggregate, summary, progress }
  }

  /* ------------------------------------------------------------------ *
   * injection
   * ------------------------------------------------------------------ */

  async preStep(payload, next) {
    const decision = await next()
    try {
      if (!this.baseConfig.inject || this.baseConfig.injectionMode === 'off') return decision
      if (decision.kind === 'reject') return decision
      const step = Number(payload?.step ?? 0)
      if (step !== 1) return decision
      const session = payload?.agent?.session
      if (!session) return decision
      const entry = this.ensureEntry(session)
      if (!entry) return decision
      await entry.ready
      if (entry.disabled || !entry.state) return decision
      const config = entry.config
      if (!config.inject || config.injectionMode === 'off') return decision
      const mode = config.injectionMode
      if (mode === 'once' && entry.state.injection) return decision
      if (mode === 'every-turn' && entry.state.injection && entry.state.injection.turn === Number(payload?.turn ?? 0)) {
        return decision
      }
      const summary = await readText(path.join(entry.ws.progressDir, 'summary.md'), '')
      if (!summary.trim()) return decision
      const otherProgress = await this.hasOtherProgress(entry.ws, entry.id)
      if (!otherProgress && (entry.state.counts?.turns ?? 0) === 0) {
        // Nothing from another session and no earlier work in this one: nothing to share yet.
        return decision
      }
      const meta = (await readJson(path.join(entry.ws.progressDir, 'meta.json'), null)) ?? {}
      const aggregate = {
        workspace: { root: entry.ws.root, name: entry.ws.name },
        totals: meta.totals ?? { sessions: otherProgress ? 2 : 1, active: 1 },
      }
      const text = renderInjection(aggregate, summary, { maxTokens: this.baseConfig.injectMaxTokens })
      markInjected(entry.state, Date.now(), entry.state.lastSeq ?? 0, Number(payload?.turn ?? 0))
      await this.flush(entry, true)
      return { ...decision, messages: [...decision.messages, createSnapshotMessage(text)] }
    } catch (error) {
      this.logWarn('injection skipped', error)
      return decision
    }
  }

  /* ------------------------------------------------------------------ *
   * commands and lifecycle hooks
   * ------------------------------------------------------------------ */

  async command(invocation) {
    const session = invocation?.agent?.session
    if (!session) return { kind: 'error', text: '当前 Session 不可用。' }
    const entry = this.ensureEntry(session)
    await entry.ready
    if (!entry.ws) return { kind: 'error', text: '无法解析当前工作区路径。' }
    const workspace = entry.ws
    const raw = String(invocation.rawInput ?? '').trim()
    const [action, ...rest] = raw.split(/\s+/)
    try {
      switch ((action || 'status').toLowerCase()) {
        case 'status':
        case 'show': {
          const summary = await readText(path.join(workspace.progressDir, 'summary.md'), '')
          if (!summary.trim()) return { kind: 'error', text: '该工作区还没有进度记录。' }
          return { kind: 'success', text: summary.trim() }
        }
        case 'sync': {
          await this.recover(entry)
          await this.flush(entry, true)
          const result = await this.refreshWorkspace(workspace)
          return { kind: 'success', text: `已强制同步。${result ? `当前共 ${result.aggregate.totals.sessions} 个 Session，测试通过 ${result.aggregate.totals.testsPassed} 项。` : ''}` }
        }
        case 'refresh': {
          const result = await this.refreshWorkspace(workspace)
          return { kind: 'success', text: result?.summary?.trim() || '已刷新，但暂无进度。' }
        }
        case 'note': {
          const text = rest.join(' ').trim()
          if (!text) return { kind: 'error', text: '用法：/progress note <要记录的技术决策或说明>' }
          this.record(entry, { type: 'note', text: sanitizeText(text, 400, entry.config), at: Date.now(), seq: entry.state.lastSeq })
          await this.flush(entry, true)
          await this.refreshWorkspace(workspace)
          return { kind: 'success', text: '已记录到本 Session 的技术决策。' }
        }
        case 'on':
        case 'off': {
          const enabled = action.toLowerCase() === 'on'
          await ensureDir(workspace.progressDir)
          const current = (await readJson(path.join(workspace.progressDir, 'config.json'), null)) ?? {}
          await writeJson(path.join(workspace.progressDir, 'config.json'), { ...current, enabled })
          entry.config = mergeWorkspaceConfig(this.baseConfig, { ...current, enabled })
          entry.disabled = !entry.config.enabled
          return { kind: 'success', text: enabled ? '已启用该工作区的进度同步。' : '已关闭该工作区的进度同步（已有文件保留）。' }
        }
        case 'archive': {
          return await this.archive(workspace)
        }
        case 'path': {
          return {
            kind: 'success',
            text: [
              `工作区：${workspace.root}`,
              `进度目录：${workspace.progressDir}`,
              `Session：${entry.id}`,
              `注入：${entry.state.injection ? `已于 ${formatTime(entry.state.injection.at)} 注入` : '尚未注入'}`,
            ].join('\n'),
          }
        }
        case 'help':
        default: {
          return {
            kind: 'success',
            text: [
              '/progress            查看当前工作区进度摘要',
              '/progress sync       强制同步当前 Session 并重算进度',
              '/progress refresh    重新生成 progress.md / summary.md',
              '/progress note <文本> 记录一条技术决策',
              '/progress on|off     启用或关闭该工作区同步',
              '/progress archive    归档超过保留期的 Session 记录',
              '/progress path       显示路径与注入状态',
            ].join('\n'),
          }
        }
      }
    } catch (error) {
      this.logWarn('command failed', error)
      return { kind: 'error', text: `进度命令失败：${error?.message ?? error}` }
    }
  }

  async archive(workspace) {
    const dir = path.join(workspace.progressDir, 'sessions')
    const files = await listFiles(dir, (name) => name.endsWith('.json'))
    const cutoff = Date.now() - this.baseConfig.retainSessionDays * 86400000
    let moved = 0
    for (const file of files) {
      const info = await stat(file).catch(() => null)
      if (!info || info.mtimeMs >= cutoff) continue
      const sessionId = path.basename(file, '.json')
      const result = await archiveSessionFiles(workspace.progressDir, sessionId)
      if (result.length > 0) moved += 1
    }
    await this.refreshWorkspace(workspace)
    return { kind: 'success', text: `已归档 ${moved} 个超过 ${this.baseConfig.retainSessionDays} 天的 Session。` }
  }
}

const WORKSPACE_SENSITIVE_EVENTS = new Set(['user/message', 'tool/call', 'tool/result', 'turn/start', 'turn/end', 'session/disposed'])

const IGNORED_EVENTS = new Set([
  'step/start',
  'step/end',
  'assistant/attempt',
  'request/header',
  'request/context',
  'session/end-seed',
  'goal/change',
  'command/run',
  'command/done',
  'title/change',
])

function compactFact(fact) {
  const { type, key, at, seq, ...rest } = fact
  const compact = { type, at, seq }
  if (key !== undefined) compact.key = key
  for (const field of ['path', 'tool', 'op', 'ok', 'command', 'exitCode', 'test', 'content', 'status', 'name', 'turn', 'text', 'runs']) {
    if (rest[field] !== undefined) compact[field] = rest[field]
  }
  return compact
}

function createSnapshotMessage(text) {
  return {
    id: randomUUID(),
    role: 'user',
    content: [{ type: 'text', text }],
    source: {
      kind: PLUGIN_NAME,
      form: 'snapshot',
      sections: [{ name: 'workspace-progress', text }],
    },
  }
}

/** Register the engine; every listener is owned by the plugin fiber. */
export function apply(ctx, rawConfig) {
  const engine = new ProgressEngine(ctx, rawConfig)

  ctx.on('session/event', (session, event) => engine.onSessionEvent(session, event))
  ctx.on('agent/pre-step', (payload, next) => engine.preStep(payload, next))
  ctx.on('agent/disposed', (payload) => {
    const id = payload?.agent?.id
    const entry = id ? engine.entries.get(id) : undefined
    if (!entry) return
    engine.enqueue(entry.session, async (target) => {
      markStatus(target.state, 'ended')
      await engine.flush(target, true)
      engine.scheduleRefresh(target.ws)
    })
  })
  ctx.on('agent/status', (payload) => {
    const id = payload?.agent?.id
    const entry = id ? engine.entries.get(id) : undefined
    if (!entry || payload.status !== 'idle') return
    engine.enqueue(entry.session, async (target) => {
      markStatus(target.state, 'idle')
      await engine.flush(target)
      engine.scheduleRefresh(target.ws)
    })
  })

  const commands = ctx.get('commands')
  if (commands && typeof commands.register === 'function') {
    ctx.effect(() =>
      commands.register({
        name: 'progress',
        description: '查看 / 同步 / 刷新当前工作区的跨 Session 进度',
        input: { hint: 'status | sync | refresh | note <文本> | on | off | archive | path' },
        handler: (invocation) => engine.command(invocation),
      }),
    )
  }

  ctx.effect(() => () => engine.dispose())
  engine.start().catch((error) => engine.logWarn('startup recovery failed', error))
  return engine
}

export { ProgressEngine }